export function getWMODetails(code: number): WMOCodeDetail {
  if (WMO_MAP[code]) {
    return WMO_MAP[code];
  }
  // Fallback for uncommon or unknown codes
  if (code >= 1 && code <= 3) return WMO_MAP[2];
  if (code >= 51 && code <= 57) return WMO_MAP[53];
  if (code >= 61 && code <= 67) return WMO_MAP[63];
  if (code >= 71 && code <= 77) return WMO_MAP[73];
  if (code >= 80 && code <= 82) return WMO_MAP[81];
  if (code >= 85 && code <= 86) return WMO_MAP[85];
  if (code >= 95) return WMO_MAP[95];

  return {
    code,
    label: 'Variable Weather',
    description: 'Weather conditions variable',
    category: 'partly_cloudy',
    icon: Wind,
    bgGradientLight: 'from-slate-500/10 via-sky-500/10 to-blue-500/5',
    cardBgLight: 'bg-slate-500/10 text-slate-900 border-slate-200/50',
    badgeBg: 'bg-slate-200 text-slate-800',
  };
}
